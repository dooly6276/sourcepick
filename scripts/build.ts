// Builds dist/web (static site), dist/chrome and dist/firefox (extensions) from src/ and lenses/.
// TypeScript in src/ is compiled to .build/ first; the compiled scripts are what gets copied.
// Usage: node scripts/build.ts [--zip]
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { ROOT, loadLenses } from "./lenses.ts";

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const SRC = path.join(ROOT, "src");
const BUILD = path.join(ROOT, ".build");
const DIST = path.join(ROOT, "dist");
const ASSETS = path.join(ROOT, "assets");

// The compiler is run from node_modules so the build needs no global install.
const tsc = path.join(ROOT, "node_modules/typescript/bin/tsc");
for (const project of ["tsconfig.json", "tsconfig.sw.json"]) {
  execFileSync(process.execPath, [tsc, "-p", path.join(ROOT, project)], { stdio: "inherit" });
}

const lenses = loadLenses();
const lensesJs = "// Generated by scripts/build.mjs from lenses/. Do not edit.\n" +
  "globalThis.SOURCE_LENSES = " + JSON.stringify(lenses.map((l) => ({
    id: l.id, region: l.region, mode: l.mode, name: l.name, sites: l.sites,
  }))) + ";\n";

const SHARED = ["core.js", "store.js", "i18n.js"];

const GOOGLE_HOSTS = ["com", "co.kr", "co.jp", "co.uk", "ca", "com.au", "de", "fr", "es", "it", "nl", "co.in", "com.br", "com.mx", "com.tw", "com.hk", "com.sg"]
  .map((tld) => `https://www.google.${tld}/search*`);
const CONTENT_MATCHES = [...GOOGLE_HOSTS, "https://www.bing.com/search*", "https://duckduckgo.com/*", "https://search.brave.com/search*"];

function reset(dir: string) { fs.rmSync(dir, { recursive: true, force: true }); fs.mkdirSync(dir, { recursive: true }); }
function copy(from: string, to: string) { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.copyFileSync(from, to); }
function write(to: string, text: string) { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.writeFileSync(to, text); }
function copyDir(from: string, to: string) { fs.cpSync(from, to, { recursive: true }); }

function common(out: string) {
  write(path.join(out, "lenses.js"), lensesJs);
  for (const f of SHARED) copy(path.join(BUILD, f), path.join(out, f));
  copy(path.join(BUILD, "app/app.js"), path.join(out, "app.js"));
  copy(path.join(SRC, "app/style.css"), path.join(out, "style.css"));
  write(path.join(out, "config.js"), CONFIG_JS);
  copy(path.join(ASSETS, "icon.svg"), path.join(out, "icons/icon.svg"));
}

// Store and repository links shown in the app ("Browser extension" section). Empty until published.
const LINKS = Object.assign({ chrome: "", firefox: "", edge: "", repo: "" }, pkg.sourcepick && pkg.sourcepick.links);
// A separate file, not an inline <script>: extension pages only run scripts from their own files (CSP script-src 'self').
const CONFIG_JS = `window.SOURCEPICK_WEB_URL = ${JSON.stringify(pkg.homepage || "")};\nwindow.SOURCEPICK_LINKS = ${JSON.stringify(LINKS)};\n`;
const CONFIG = '<script src="config.js"></script>';

function html({ head = "", redirect = "", bodyClass = "" } = {}) {
  let s = fs.readFileSync(path.join(SRC, "app/index.html"), "utf8");
  s = s.replace("<!--web-head-->", head).replace("<!--web-redirect-->", redirect);
  if (bodyClass) s = s.replace("<body>", `<body class="${bodyClass}">`);
  return s.replace(/\n\s*<!--[a-z-]+-->/g, "");
}

function buildWeb() {
  const out = path.join(DIST, "web");
  reset(out);
  common(out);
  copy(path.join(BUILD, "web/redirect.js"), path.join(out, "redirect.js"));
  copy(path.join(SRC, "web/manifest.webmanifest"), path.join(out, "manifest.webmanifest"));
  write(path.join(out, "sw.js"), fs.readFileSync(path.join(BUILD, "web/sw.js"), "utf8").replace("__VERSION__", pkg.version));
  for (const f of ["icon-192.png", "icon-512.png", "icon-maskable-512.png", "icon-32.png"]) copy(path.join(ASSETS, f), path.join(out, "icons", f));
  // Lets browsers (Chrome on Android and computers, Firefox) offer Sourcepick as a search engine.
  const home = (pkg.homepage || "").replace(/\/?$/, "/");
  write(path.join(out, "opensearch.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<OpenSearchDescription xmlns="http://a9.com/-/spec/opensearch/1.1/">
  <ShortName>Sourcepick</ShortName>
  <Description>Search only the sites you choose</Description>
  <InputEncoding>UTF-8</InputEncoding>
  <Image width="32" height="32" type="image/png">${home}icons/icon-32.png</Image>
  <Url type="text/html" method="get" template="${home}?q={searchTerms}"/>
</OpenSearchDescription>
`);
  write(path.join(out, "index.html"), html({
    head: '<link rel="manifest" href="manifest.webmanifest">\n  <link rel="apple-touch-icon" href="icons/icon-192.png">\n  <link rel="search" type="application/opensearchdescription+xml" title="Sourcepick" href="opensearch.xml">',
    redirect: CONFIG + '\n  <script src="redirect.js"></script>',
  }));
  return out;
}

function manifest(target: "chrome" | "firefox") {
  const m: Record<string, unknown> = {
    manifest_version: 3,
    name: "__MSG_name__",
    description: "__MSG_description__",
    default_locale: "en",
    version: pkg.version,
    homepage_url: pkg.homepage,
    icons: { 16: "icons/icon-16.png", 32: "icons/icon-32.png", 48: "icons/icon-48.png", 128: "icons/icon-128.png" },
    action: { default_popup: "popup.html", default_icon: { 16: "icons/icon-16.png", 32: "icons/icon-32.png" } },
    options_ui: { page: "index.html", open_in_tab: true },
    omnibox: { keyword: "sp" },
    permissions: ["storage"],
    content_scripts: [{
      matches: CONTENT_MATCHES,
      js: ["lenses.js", ...SHARED, "content.js"],
      css: ["content.css"],
      run_at: "document_idle",
    }],
  };
  if (target === "chrome") {
    m.background = { service_worker: "background.js" };
  } else {
    m.background = { scripts: ["lenses.js", ...SHARED, "background.js"] };
    // Firefox asks every add-on to declare what it collects; Sourcepick collects nothing.
    m.browser_specific_settings = {
      gecko: { id: "sourcepick@dooly6276.github.io", strict_min_version: "121.0", data_collection_permissions: { required: ["none"] } },
      gecko_android: { strict_min_version: "121.0" },
    };
  }
  return m;
}

function buildExtension(target: "chrome" | "firefox") {
  const out = path.join(DIST, target);
  reset(out);
  common(out);
  for (const f of ["content.js", "background.js"]) copy(path.join(BUILD, "extension", f), path.join(out, f));
  copy(path.join(SRC, "extension/content.css"), path.join(out, "content.css"));
  copyDir(path.join(SRC, "extension/_locales"), path.join(out, "_locales"));
  for (const n of [16, 32, 48, 128]) copy(path.join(ASSETS, `icon-${n}.png`), path.join(out, `icons/icon-${n}.png`));
  write(path.join(out, "index.html"), html({ redirect: CONFIG }));
  write(path.join(out, "popup.html"), html({ bodyClass: "popup", redirect: CONFIG }));
  write(path.join(out, "manifest.json"), JSON.stringify(manifest(target), null, 2) + "\n");
  return out;
}

const outs = [buildWeb(), buildExtension("chrome"), buildExtension("firefox")];
console.log(`${lenses.length} lenses, version ${pkg.version}`);
for (const o of outs) console.log("  " + path.relative(ROOT, o));

if (process.argv.includes("--zip")) {
  for (const target of ["chrome", "firefox"]) {
    const zip = path.join(DIST, `sourcepick-${target}-${pkg.version}.zip`);
    fs.rmSync(zip, { force: true });
    execFileSync("zip", ["-qr", zip, "."], { cwd: path.join(DIST, target) });
    console.log("  " + path.relative(ROOT, zip));
  }
}
